const assert = require('node:assert/strict');
const createGame = (opts=>require('./harness156.cjs')({legacyTerrain166:true,...opts}));
(async () => {
  const g = createGame(), {run,w} = g;
  assert.equal(g.plays,0);
  assert(!w.document.querySelector('script[src*="audio155"]'));
  assert.equal(w.document.querySelectorAll('.effects-button156').length,2);
  for (const map of ['east','west']) {
    run(`activateAtlasGeometry('${map}');reset();atlasMenuOpen=false;closeModal();S.tutorial123=null;S.interruption=null;S.points=100000;S.lines=[];S.vehicles=[];S.cities=Array.from({length:7},(_,id)=>({...S.cities[0],id,x:100+id*200,y:500,shape:id%3,color:id%3,dormant:false,removed:false,q:[]}));requirements=()=>({bridge:0,tunnel:0,hill:0});`);
    const down=id=>run(`beginPointer({pointerId:77,clientX:toScreen(S.cities[${id}]).x,clientY:toScreen(S.cities[${id}]).y})`);
    const move=id=>run(`movePointer({pointerId:77,clientX:toScreen(S.cities[${id}]).x,clientY:toScreen(S.cities[${id}]).y})`);
    const up=id=>run(`finishPointer({pointerId:77,type:'pointerup',clientX:toScreen(S.cities[${id}]).x,clientY:toScreen(S.cities[${id}]).y})`);
    let before=g.plays;
    down(0);assert.equal(g.plays,before,'origin is silent');
    move(1);assert.equal(g.plays,++before,'next city sounds before confirmation');
    assert.equal(run('S.lines.length'),0,'still only a draft');
    move(1);move(1);assert.equal(g.plays,before,'hover does not repeat');
    move(2);assert.equal(g.plays,++before,'third city sounds without lifting');
    up(2);assert.equal(g.plays,before,'release does not repeat');
    run('commitDraft(true)');assert.equal(g.plays,before,'confirm is silent');
    run('clearSelection()');down(2);move(3);assert.equal(g.plays,++before,'tail extension sounds immediately');
    move(4);assert.equal(g.plays,++before,'continuous tail extension sounds at every city');
    up(4);run('commitDraft(true);clearSelection()');assert.equal(g.plays,before);
    down(0);move(5);assert.equal(g.plays,++before,'head extension sounds immediately');
    move(6);assert.equal(g.plays,++before);up(6);run('cancelDraft(false)');assert.equal(g.plays,before,'cancel is silent');
    run('clearSelection()');down(4);move(4);up(4);assert.equal(g.plays,before,'tap existing city is silent');
    run('clearSelection();requirements=()=>({bridge:0,tunnel:0,hill:0,invalid:"blocked"});');
    down(4);move(6);assert.equal(g.plays,before,'invalid snap is silent');up(6);run('cancelDraft(false)');
  }
  run('setEffects156("enabled",false);playConnect156()');
  let before=g.plays;
  assert.equal(JSON.parse(w.localStorage.getItem('transit-effects-v1')).enabled,false);
  run('openEffects156()');assert.equal(w.document.querySelector('#effects-on156').getAttribute('aria-pressed'),'false');
  run('setEffects156("volume",.2);setEffects156("enabled",true);playConnect156()');
  assert.equal(run('effect156.volume'),.2);assert.equal(g.plays,before+1);
  g.setHidden(true);before=g.plays;run('playConnect156()');assert.equal(g.plays,before);
  g.setHidden(false);assert.equal(g.plays,before,'return does not replay a completed effect');
  w.dispatchEvent(new w.Event('pagehide'));run('playConnect156()');assert.equal(g.plays,before);
  w.dispatchEvent(new w.Event('pageshow'));
  g.setRejected(true);run('playConnect156()');await new Promise(r=>setImmediate(r));
  g.setRejected(false);run('playConnect156()');await new Promise(r=>setImmediate(r));
  assert.equal(g.plays,before+2,'blocked playback can recover');
  run('window.transitAndroidBackground13=true;playConnect156()');assert.equal(g.plays,before+2);
  assert.equal(g.errors.length,0);
  const saved=JSON.parse(w.localStorage.getItem('transit-effects-v1'));g.dom.window.close();
  const next=createGame({prefs:saved});assert.equal(next.run('effectsPrefs156.volume'),.2);assert.equal(next.run('effectsPrefs156.enabled'),true);next.dom.window.close();
  const blocked=createGame({blockStorage:true});blocked.run('setEffects156("enabled",false);setEffects156("volume",.2)');blocked.dom.window.close();
  console.log('PASS both maps: immediate per-city snap sound on new lines and either-end extensions, silent hover/release/confirm/cancel/rejection, toggle/volume/reload, background, play/storage failure recovery');
})();
